#!/usr/bin/env python3
"""Generate the agg-tunnel CLI reference from a current Aggligator checkout."""

import argparse
import html
import json
from pathlib import Path
import subprocess
import sys
import textwrap
import tomllib


FEATURES = "bluer,usb-host,usb-device"
COMMANDS = (
    ("agg-tunnel", "AGG-TUNNEL", ()),
    ("agg-tunnel-client", "AGG-TUNNEL CLIENT", ("client",)),
    ("agg-tunnel-server", "AGG-TUNNEL SERVER", ("server",)),
    ("agg-tunnel-show-cfg", "AGG-TUNNEL SHOW-CFG", ("show-cfg",)),
)


def format_help(help_text: str) -> str:
    lines = []
    for line in help_text.splitlines():
        line = line.expandtabs().rstrip()
        indent = line[:len(line) - len(line.lstrip())]
        lines.append(textwrap.fill(
            line.lstrip(), width=80, initial_indent=indent, subsequent_indent=indent,
            break_long_words=False, break_on_hyphens=False,
        ))
    return "\n".join(lines).strip()


def render(version: str, help_sections: list[str]) -> str:
    sections = []
    for (anchor, heading, _), help_text in zip(COMMANDS, help_sections, strict=True):
        if "{% endraw %}" in help_text:
            raise ValueError("CLI documentation contains a Liquid raw-block terminator")
        escaped = html.escape(format_help(help_text), quote=False)
        sections.append(
            f'                <h2 id="{anchor}">{heading}</h2>\n'
            f'                <pre class="cmd">{{% raw %}}{escaped}{{% endraw %}}</pre>'
        )
    return f"""---
layout: base
project: aggligator
title: "agg-tunnel command-line reference"
description: >-
  Subcommands, options and defaults for agg-tunnel, generated from Clap.
  Includes TCP, SOCKS5 and optional Bluetooth and USB transport flags.
canonical: /aggligator/agg-tunnel-cli.html
favicon: /aggligator/logo.png
nav_url: /aggligator/tunnel.html
cli_version: {json.dumps(version)}
cli_features: {json.dumps(FEATURES)}
---
""" + """
<!-- Generated by _tools/render_tunnel_cli.py. Regenerate rather than editing this page. -->

    <header class="page-header">
        {% include nav.html %}
        <div class="wrap narrow">
            <h1><code>agg-tunnel</code> command-line reference</h1>
            <p>
                Version {{ page.cli_version }} &middot;
                <a href="/aggligator/tunnel.html">Installation and usage examples</a>
            </p>
            <p>Install on Linux with all features:</p>
            <pre class="cmd"><code>cargo install aggligator-util --all-features</code></pre>
            <nav aria-label="Commands">
                <a href="#agg-tunnel">Overview</a> &middot;
                <a href="#agg-tunnel-client">Client</a> &middot;
                <a href="#agg-tunnel-server">Server</a> &middot;
                <a href="#agg-tunnel-show-cfg">Default configuration</a>
            </nav>
        </div>
    </header>

    <main id="content">
        <section class="section">
            <div class="wrap narrow cli-reference">
""" + "\n\n".join(sections) + """
            </div>
        </section>
    </main>
"""


def main() -> int:
    root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repo", nargs="?", type=Path, default=root.parent / "aggligator",
                        help="Path to the Aggligator source checkout")
    parser.add_argument("--check", action="store_true", help="Fail if the generated page is out of date")
    args = parser.parse_args()
    if sys.platform != "linux":
        parser.error("Generate on Linux so Bluetooth and USB device options can be included")
    repo = args.repo.resolve()
    try:
        manifest = tomllib.loads((repo / "aggligator-util/Cargo.toml").read_text(encoding="utf-8"))
        version = manifest["package"]["version"]
        if not isinstance(version, str):
            raise ValueError("Expected aggligator-util to declare a package version")
        cargo = [
            "cargo", "run", "--quiet", "--locked", "--manifest-path", str(repo / "Cargo.toml"),
            "-p", "aggligator-util", "--bin", "agg-tunnel", "--no-default-features",
            "--features", FEATURES, "--",
        ]
        help_sections = [
            subprocess.run(
                [*cargo, *command, "--help"], cwd=repo, check=True,
                text=True, stdout=subprocess.PIPE,
            ).stdout
            for _, _, command in COMMANDS
        ]
        content = render(version, help_sections)
        target = root / "aggligator/agg-tunnel-cli.html"
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != content:
                print("agg-tunnel CLI reference is out of date; rerun _tools/render_tunnel_cli.py",
                      file=sys.stderr)
                return 1
            print("agg-tunnel CLI reference is up to date")
        else:
            target.write_text(content, encoding="utf-8")
            print(f"Generated {target.relative_to(root)} for aggligator-util {version}")
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        print(f"Cannot generate agg-tunnel CLI reference: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
